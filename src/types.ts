// date formatting
export function formatYear(year: number): string {
  return year < 0 ? `${-year} BCE` : `${year} CE`;
}

export function formatEventDate(e: Pick<RomeEvent, 'year' | 'yearEnd' | 'dateNote'>): string {
  const base =
    e.yearEnd != null && e.yearEnd !== e.year
      ? e.year < 0 && e.yearEnd < 0
        ? `${-e.year}–${-e.yearEnd} BCE`
        : e.year < 0 && e.yearEnd >= 0
          ? `${-e.year} BCE – ${e.yearEnd} CE`
          : `${e.year}–${e.yearEnd} CE`
      : formatYear(e.year);
  return e.dateNote ? `${base} (${e.dateNote})` : base;
}
