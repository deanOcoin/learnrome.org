export interface Source {
  author: string;
  work: string;
  note?: string;
}

export type MarkerType = 'battle' | 'siege' | 'political' | 'founding' | 'disaster';

export interface Marker {
  type: MarkerType;
  label: string;
  at: [number, number]; // lon, lat
}

export interface Movement {
  label: string;
  path: [number, number][]; // lon, lat waypoints
  kind?: 'march' | 'migration' | 'sea';
}

export interface RomeEvent {
  id: string;              // 'cannae-216bce', stable and URL-safe, never renumber
  year: number;            // negative = BCE; -216 means 216 BCE (no astronomical year 0)
  yearEnd?: number;        // for spans
  dateNote?: string;       // 'traditional', 'c.', 'March 15'
  era: EraId;
  title: string;
  headline: string;        // one sentence
  body: string;            // 3-8 paragraphs, blank-line separated
  whyItMatters: string;    // the causal argument, not a summary
  misconception?: {
    claim: string;
    correction: string;
  };
  control: Partial<Record<RegionId, ControlStatus>>; // DELTA from previous event
  nonTerritorial?: boolean;
  spatialFocus?: RegionId[];
  markers?: Marker[];
  movements?: Movement[];
  sources: Source[];
  connects?: string[];     // event IDs this causally depends on
  weight: 1 | 2 | 3;
  reliability: Reliability;
  tags: Tag[];
}

