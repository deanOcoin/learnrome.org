// control status. rivals get separate hues, everything Roman lives on one warm ramp
export type RivalId =
  | 'carthage'    // Carthage
  | 'hellenistic' // Macedon, the Seleucids, the Ptolemies, Pergamon, Pyrrhus, Pontus
  | 'parthia'     // Parthia, then the Sassanids (same seat, same hue)
  | 'celtic'      // independent Gauls, pre-conquest Britain
  | 'germanic'    // Goths, Vandals, Franks, the successor kingdoms
  | 'steppe';     // the Huns and steppe powers

export type RomanStatus =
  | 'core'        // integrated, taxed, culturally Roman, not going anywhere
  | 'provincial'  // formally a province, garrisoned, recently acquired or restive
  | 'client'      // client kingdom / allied state, Roman-aligned but not Roman-administered
  | 'contested'   // active campaigning, control genuinely in doubt this year
  | 'transient'   // held, but historians know it won't last
  | 'breakaway'   // Roman population and institutions, in secession
  | 'lost'        // formerly Roman, only shown once it has actually been Roman
  | 'unshown';    // outside the story right now

export type ControlStatus = RomanStatus | `rival-${RivalId}`;

export function isRival(s: ControlStatus): s is `rival-${RivalId}` {
  return s.startsWith('rival-');
}

