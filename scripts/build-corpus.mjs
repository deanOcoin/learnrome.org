// splits the authored corpus into generated/light.gen.ts (every event minus prose) and
// one lazy prose-<era>.gen.ts per era. npm run build:corpus, and npm run build runs it first.

import { writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { build } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const outDir = join(root, 'src/data/events/generated');

// bundle first: node can strip types but its ESM resolver wants file extensions,
// and the era modules are written extensionless
const tmp = join(root, 'node_modules/.tmp/corpus-source.mjs');
mkdirSync(dirname(tmp), { recursive: true });
await build({
  entryPoints: [join(root, 'src/data/events/full.ts')],
  outfile: tmp,
  bundle: true,
  format: 'esm',
  platform: 'node',
  logLevel: 'silent',
});
const { FULL_EVENTS, PROSE_KEYS } = await import(pathToFileURL(tmp).href);
rmSync(tmp, { force: true });

mkdirSync(outDir, { recursive: true });

const HEADER = `// GENERATED by scripts/build-corpus.mjs — do not edit.
// Source of truth: the authored era modules in src/data/events/.
// Regenerate with: npm run build:corpus\n`;

// light index: every event minus prose, in final sorted order
const light = FULL_EVENTS.map((e) => {
  const out = {};
  for (const [k, v] of Object.entries(e)) if (!PROSE_KEYS.includes(k)) out[k] = v;
  return out;
});

writeFileSync(
  join(outDir, 'light.gen.ts'),
  `${HEADER}
import type { LightEvent } from '../full';

export const LIGHT_EVENTS: LightEvent[] = ${JSON.stringify(light, null, 0)};
`,
  'utf8'
);

// one prose module per era so a reader downloads only the stretch they open
const byEra = new Map();
for (const e of FULL_EVENTS) {
  const prose = {};
  for (const k of PROSE_KEYS) if (e[k] !== undefined) prose[k] = e[k];
  if (!byEra.has(e.era)) byEra.set(e.era, {});
  byEra.get(e.era)[e.id] = prose;
}

const eras = [...byEra.keys()].sort();
for (const era of eras) {
  writeFileSync(
    join(outDir, `prose-${era}.gen.ts`),
    `${HEADER}
import type { Prose } from '../full';

const PROSE: Record<string, Prose> = ${JSON.stringify(byEra.get(era), null, 0)};
export default PROSE;
`,
    'utf8'
  );
}

// literal dynamic imports so Vite sees every chunk; a template-literal import would bundle them all
writeFileSync(
  join(outDir, 'prose-index.gen.ts'),
  `${HEADER}
import type { Prose } from '../full';

export type EraKey = ${eras.map((e) => JSON.stringify(e)).join(' | ')};

export const PROSE_ERAS: EraKey[] = ${JSON.stringify(eras)};

export function importProse(era: EraKey): Promise<{ default: Record<string, Prose> }> {
  switch (era) {
${eras.map((e) => `    case ${JSON.stringify(e)}:\n      return import('./prose-${e}.gen');`).join('\n')}
    default:
      throw new Error('Unknown era: ' + era);
  }
}
`,
  'utf8'
);

const kb = (s) => Math.round(s / 1024);
const lightBytes = JSON.stringify(light).length;
const proseBytes = [...byEra.values()].reduce((n, o) => n + JSON.stringify(o).length, 0);
console.log(`build-corpus: ${FULL_EVENTS.length} events`);
console.log(`  light.gen.ts        ${kb(lightBytes)} KB  (loaded immediately)`);
console.log(`  prose × ${eras.length} eras      ${kb(proseBytes)} KB  (loaded on demand)`);
console.log(`  deferred: ${Math.round((proseBytes / (lightBytes + proseBytes)) * 100)}% of the corpus`);
